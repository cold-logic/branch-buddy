                cmd="branch__buddy__subcmd__help__subcmd__new"
                ;;
            branch__buddy__subcmd__help,set-base)
                cmd="branch__buddy__subcmd__help__subcmd__set__subcmd__base"
                ;;
            branch__buddy__subcmd__help,tree)
                cmd="branch__buddy__subcmd__help__subcmd__tree"
                ;;
            *)
                ;;
        esac
    done

    case "${cmd}" in
        branch__buddy)
            opts="-h --config --help new get-base set-base has-base guess-base tree install-hooks doctor log init completions help"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 1 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                --config)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        branch__subcmd__buddy__subcmd__completions)
            opts="-h --config --help bash elvish fish powershell zsh"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                --config)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        branch__subcmd__buddy__subcmd__doctor)
            opts="-h --fix --install-hook --config --help"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                --config)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                *)
                    COMPREPLY=()
                    ;;
            esac
