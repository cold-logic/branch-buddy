_branch-buddy() {
    local i cur prev opts cmd
    COMPREPLY=()
    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
        cur="$2"
    else
        cur="${COMP_WORDS[COMP_CWORD]}"
    fi
    prev="$3"
    cmd=""
    opts=""

    for i in "${COMP_WORDS[@]:0:COMP_CWORD}"
    do
        case "${cmd},${i}" in
            ",$1")
                cmd="branch__buddy"
                ;;
            branch__buddy,completions)
                cmd="branch__buddy__subcmd__completions"
                ;;
            branch__buddy,doctor)
                cmd="branch__buddy__subcmd__doctor"
                ;;
            branch__buddy,get-base)
                cmd="branch__buddy__subcmd__get__subcmd__base"
                ;;
            branch__buddy,guess-base)
                cmd="branch__buddy__subcmd__guess__subcmd__base"
                ;;
            branch__buddy,has-base)
                cmd="branch__buddy__subcmd__has__subcmd__base"
                ;;
            branch__buddy,help)
                cmd="branch__buddy__subcmd__help"
                ;;
            branch__buddy,init)
                cmd="branch__buddy__subcmd__init"
                ;;
            branch__buddy,install-hooks)
                cmd="branch__buddy__subcmd__install__subcmd__hooks"
                ;;
            branch__buddy,log)
                cmd="branch__buddy__subcmd__log"
                ;;
            branch__buddy,new)
                cmd="branch__buddy__subcmd__new"
                ;;
            branch__buddy,set-base)
                cmd="branch__buddy__subcmd__set__subcmd__base"
                ;;
            branch__buddy,tree)
                cmd="branch__buddy__subcmd__tree"
                ;;
            branch__buddy__subcmd__help,completions)
                cmd="branch__buddy__subcmd__help__subcmd__completions"
                ;;
            branch__buddy__subcmd__help,doctor)
                cmd="branch__buddy__subcmd__help__subcmd__doctor"
                ;;
            branch__buddy__subcmd__help,get-base)
                cmd="branch__buddy__subcmd__help__subcmd__get__subcmd__base"
                ;;
            branch__buddy__subcmd__help,guess-base)
                cmd="branch__buddy__subcmd__help__subcmd__guess__subcmd__base"
                ;;
            branch__buddy__subcmd__help,has-base)
                cmd="branch__buddy__subcmd__help__subcmd__has__subcmd__base"
                ;;
            branch__buddy__subcmd__help,help)
                cmd="branch__buddy__subcmd__help__subcmd__help"
                ;;
            branch__buddy__subcmd__help,init)
                cmd="branch__buddy__subcmd__help__subcmd__init"
                ;;
            branch__buddy__subcmd__help,install-hooks)
                cmd="branch__buddy__subcmd__help__subcmd__install__subcmd__hooks"
                ;;
